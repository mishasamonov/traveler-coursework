package ua.edu.sumdu.traveler.core.port;

import java.util.Optional;
import java.util.UUID;
import ua.edu.sumdu.traveler.core.domain.PageResult;
import ua.edu.sumdu.traveler.core.domain.PlanSearchCriteria;
import ua.edu.sumdu.traveler.core.domain.PlanSummary;
import ua.edu.sumdu.traveler.core.domain.TravelPlan;
import ua.edu.sumdu.traveler.core.domain.TravelStatistics;

/** Data access to travel plans. Implemented by the persistence module (JPA). */
public interface TravelPlanPort {

  Optional<TravelPlan> findById(UUID id);

  /**
   * Reads the plan and locks its row until the end of the transaction (SELECT ... FOR UPDATE).
   * Every change of the route takes this lock first, so two requests cannot give two locations the
   * same position.
   */
  Optional<TravelPlan> lockById(UUID id);

  /** Inserts a new plan with version 1; the id is generated by the implementation. */
  TravelPlan insert(TravelPlan plan);

  /**
   * Saves the plan if plan.version() still equals the stored version and returns it with the next
   * version.
   *
   * @throws ua.edu.sumdu.traveler.core.error.ConflictException when the stored version differs
   */
  TravelPlan update(TravelPlan plan);

  /** Deletes the plan; its locations are removed by ON DELETE CASCADE. */
  void deleteById(UUID id);

  PageResult<PlanSummary> search(PlanSearchCriteria criteria);

  TravelStatistics statistics();
}
